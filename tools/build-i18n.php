<?php
// INFO: builds the static language versions of the site pages – run on every deploy:
//       php tools/build-i18n.php [--site=https://news-reader.app/]
//       i18n/en.json is the single text source; <page> markup + i18n/<lang>.json → <lang>/<page>,
//       hreflang alternates, sitemap.xml, og:image per language (og-image-<lang>.png from tools/build-og-images.mjs). One static page per language because search engines index one language per URL.
//       EXTRA_PAGES (single-language) only get their canonical updated and a sitemap entry.
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

const LANGS   = ['en', 'de', 'fr', 'it', 'es'];          // INFO: first = x-default, served at "/"
const LOCALES = ['en' => 'en_US', 'de' => 'de_DE', 'fr' => 'fr_FR', 'it' => 'it_IT', 'es' => 'es_ES'];
const PAGES   = ['index.html' => true, 'privacy.html' => true, 'imprint.html' => true, 'thanks.html' => false, '404.html' => null]; // INFO: page => listed in sitemap; null = error page (see below)
const EXTRA_PAGES = ['app/', 'docs/api/'];                // INFO: path relative to --site, file = <path>index.html
// INFO: nginx serves the error page at any missing address (error_page), so its links are absolute and point into its language;
//       it has no canonical, no alternates and no sitemap entry (noindex)

$root = dirname(__DIR__);
$opts = getopt('', ['site::']);
$site = rtrim((string)($opts['site'] ?? 'https://news-reader.app/'), '/') . '/';

$en = load_json("$root/i18n/en.json");
$tEn = fn(string $key): ?string => lookup($en, $key);
$dicts = [];
foreach (array_slice(LANGS, 1) as $lang) $dicts[$lang] = array_replace_recursive($en, load_json("$root/i18n/$lang.json"));

$sitemapUrls = [];
foreach (PAGES as $page => $listed) {
    $sourceFile = "$root/$page";
    $source = file_get_contents($sourceFile);
    if ($source === false) fail("$page not found");

    $urls = [];
    foreach (LANGS as $i => $lang) $urls[$lang] = $site . ($i === 0 ? '' : "$lang/") . ($page === 'index.html' ? '' : $page);
    if ($listed) $sitemapUrls[] = $urls;
    $errorPage = $listed === null;

    $alternates = '';
    foreach (LANGS as $lang) {
        $alternates .= "  <link rel=\"alternate\" hreflang=\"$lang\" href=\"{$urls[$lang]}\">\n";
    }
    $alternates .= "  <link rel=\"alternate\" hreflang=\"x-default\" href=\"{$urls[LANGS[0]]}\">\n";

    $updated = translate_attributes(translate_elements($source, $tEn), $tEn);
    if (!$errorPage) $updated = set_alternates($updated, $alternates, $page);
    $updated = set_canonical($updated, $urls[LANGS[0]]);
    $updated = preg_replace('/(<meta property="og:url" content=")[^"]*(")/', '${1}' . $urls[LANGS[0]] . '${2}', $updated, 1);
    $updated = preg_replace('/(<meta (?:property="og:image"|name="twitter:image") content=")[^"]*(")/', '${1}' . $site . 'og-image.png${2}', $updated);
    $updated = update_jsonld($updated, $en, $urls[LANGS[0]], LANGS[0], false);
    if ($updated !== $source) file_put_contents($sourceFile, $updated);
    echo "✓ $page (en" . ($updated !== $source ? ', updated' : ', unchanged') . ")\n";

    foreach (array_slice(LANGS, 1) as $lang) {
        $dict = $dicts[$lang];
        $t = fn(string $key): ?string => lookup($dict, $key);

        $html = $updated;
        $html = translate_elements($html, $t);
        $html = translate_attributes($html, $t);
        $html = $errorPage
            ? localize_absolute_urls(preg_replace('/<html lang="[^"]*"/', "<html lang=\"$lang\"", $html, 1), "/$lang/")
            : preg_replace('/<html lang="[^"]*" data-root="[^"]*">/', "<html lang=\"$lang\" data-root=\"../\">", $html, 1);
        $html = set_canonical($html, $urls[$lang]);
        $html = preg_replace('/(<meta property="og:url" content=")[^"]*(")/', '${1}' . $urls[$lang] . '${2}', $html, 1);
        $html = preg_replace('/(<meta property="og:locale" content=")[^"]*(")/', '${1}' . LOCALES[$lang] . '${2}', $html, 1);
        if (is_file("$root/og-image-$lang.png")) {
            $html = preg_replace('/(<meta (?:property="og:image"|name="twitter:image") content=")[^"]*(")/', '${1}' . $site . "og-image-$lang.png" . '${2}', $html);
        }
        $html = rewrite_relative_urls($html, '../');
        $html = str_replace(["from './app/js/i18n.js'", "<option value=\"$lang\">"], ["from '../app/js/i18n.js'", "<option value=\"$lang\" selected>"], $html);
        $html = update_jsonld($html, $dict, $urls[$lang], $lang);
        $html = "<!-- Generated by tools/build-i18n.php from $page + i18n/$lang.json – do not edit. -->\n" . $html;

        if (!is_dir("$root/$lang")) mkdir("$root/$lang", 0775, true);
        file_put_contents("$root/$lang/$page", $html);
        echo "✓ $lang/$page\n";
    }
}
foreach (array_slice(LANGS, 1) as $lang) {
    $missing = count_missing($en, load_json("$root/i18n/$lang.json"));
    if ($missing) echo "  $lang: $missing keys fall back to English\n";
}

foreach (EXTRA_PAGES as $path) {
    $file = "$root/{$path}index.html";
    $html = file_get_contents($file);
    if ($html === false) fail("$path" . 'index.html not found');
    $new = set_canonical($html, $site . $path);
    if ($new !== $html) file_put_contents($file, $new);
    echo "✓ {$path}index.html (canonical" . ($new !== $html ? ', updated' : ', unchanged') . ")\n";
}

$today = gmdate('Y-m-d');
$xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
     . "<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\" xmlns:xhtml=\"http://www.w3.org/1999/xhtml\">\n";
foreach ($sitemapUrls as $urls) {
    foreach (LANGS as $lang) {
        $xml .= "  <url>\n    <loc>{$urls[$lang]}</loc>\n    <lastmod>$today</lastmod>\n";
        foreach (LANGS as $alt) {
            $xml .= "    <xhtml:link rel=\"alternate\" hreflang=\"$alt\" href=\"{$urls[$alt]}\"/>\n";
        }
        $xml .= "    <xhtml:link rel=\"alternate\" hreflang=\"x-default\" href=\"{$urls[LANGS[0]]}\"/>\n  </url>\n";
    }
}
foreach (EXTRA_PAGES as $path) {
    $xml .= "  <url>\n    <loc>$site$path</loc>\n    <lastmod>$today</lastmod>\n  </url>\n";
}
$xml .= "</urlset>\n";
file_put_contents("$root/sitemap.xml", $xml);
echo "✓ sitemap.xml (" . (count($sitemapUrls) * count(LANGS) + count(EXTRA_PAGES)) . " URLs)\n";

function fail(string $msg): never
{
    fwrite(STDERR, "✗ $msg\n");
    exit(1);
}

function load_json(string $file): array
{
    if (!is_file($file)) return [];
    $data = json_decode((string)file_get_contents($file), true);
    if (!is_array($data)) fail("invalid JSON: $file");
    return $data;
}

function lookup(array $dict, string $key): ?string
{
    $v = $dict;
    foreach (explode('.', $key) as $part) {
        if (!is_array($v) || !array_key_exists($part, $v)) return null;
        $v = $v[$part];
    }
    return is_string($v) ? $v : null;
}

function count_missing(array $en, array $other, string $prefix = ''): int
{
    $n = 0;
    foreach ($en as $k => $v) {
        if (is_array($v)) $n += count_missing($v, is_array($other[$k] ?? null) ? $other[$k] : [], "$prefix$k.");
        elseif (!isset($other[$k])) $n++;
    }
    return $n;
}

function translate_elements(string $html, callable $t): string
{
    $out = '';
    $pos = 0;
    while (preg_match('/<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*?\sdata-i18n="([^"]+)"[^>]*>/', $html, $m, PREG_OFFSET_CAPTURE, $pos)) {
        $tag = strtolower($m[1][0]);
        $openEnd = $m[0][1] + strlen($m[0][0]);
        $close = find_close($html, $tag, $openEnd);
        if ($close === null) fail("unclosed <$tag data-i18n=\"{$m[2][0]}\">");
        $value = $t($m[2][0]);
        $out .= substr($html, $pos, $openEnd - $pos) . ($value ?? substr($html, $openEnd, $close - $openEnd));
        $pos = $close;
    }
    return $out . substr($html, $pos);
}

// INFO: offset of the closing tag matching the element opened right before $from
function find_close(string $html, string $tag, int $from): ?int
{
    $depth = 1;
    $i = $from;
    while (preg_match('/<(\/?)' . preg_quote($tag, '/') . '\b[^>]*>/i', $html, $m, PREG_OFFSET_CAPTURE, $i)) {
        $depth += $m[1][0] === '/' ? -1 : 1;
        if ($depth === 0) return $m[0][1];
        $i = $m[0][1] + strlen($m[0][0]);
    }
    return null;
}

function translate_attributes(string $html, callable $t): string
{
    return preg_replace_callback('/<[a-zA-Z][^>]*\sdata-i18n-attr="([^"]+)"[^>]*>/', function ($m) use ($t) {
        $tag = $m[0];
        foreach (explode(';', $m[1]) as $pair) {
            [$attr, $key] = array_map('trim', explode(':', $pair, 2) + [1 => '']);
            $value = $t($key);
            if ($attr === '' || $value === null) continue;
            $value = htmlspecialchars(html_entity_decode(strip_tags($value), ENT_QUOTES | ENT_HTML5, 'UTF-8'), ENT_QUOTES, 'UTF-8');
            $tag = preg_replace('/(\s' . preg_quote($attr, '/') . '=")[^"]*(")/', '${1}' . str_replace(['\\', '$'], ['\\\\', '\\$'], $value) . '${2}', $tag, 1);
        }
        return $tag;
    }, $html);
}

// INFO: error page – links to the start page (and its sections) and the legal pages lead into the page's language;
//       links with hreflang (the language list) stay as they are
function localize_absolute_urls(string $html, string $prefix): string
{
    return preg_replace_callback('/<a\s[^>]*>/', fn($m) => str_contains($m[0], 'hreflang=')
        ? $m[0]
        : preg_replace('/(\shref=")\/((?:#[\w-]+|privacy\.html|imprint\.html)?")/', '${1}' . $prefix . '${2}', $m[0]), $html);
}

// INFO: pages in /<lang>/ live one level deeper – relative href/src get a prefix.
//       "./…" marks a link to the page of the same language (./, ./privacy.html) and is kept as is.
function rewrite_relative_urls(string $html, string $prefix): string
{
    return preg_replace('/(\s(?:href|src)=")(?![a-z][a-z0-9+.-]*:|#|\/|\.\.\/|\.\/)/i', '${1}' . $prefix, $html);
}

function set_alternates(string $html, string $block, string $page): string
{
    $re = '/(<!-- i18n:alternates[^>]*-->\n)(.*?)([ \t]*<!-- \/i18n:alternates -->)/s';
    if (!preg_match($re, $html)) fail("marker <!-- i18n:alternates --> missing in $page");
    return preg_replace_callback($re, fn($m) => $m[1] . $block . $m[3], $html, 1);
}

function set_canonical(string $html, string $url): string
{
    return preg_replace('/(<link rel="canonical" href=")[^"]*(")/', '${1}' . $url . '${2}', $html, 1);
}

function update_jsonld(string $html, array $dict, string $url, string $lang, bool $description = true): string
{
    return preg_replace_callback('/(<script type="application\/ld\+json">)(.*?)(<\/script>)/s', function ($m) use ($html, $dict, $url, $lang, $description) {
        $data = json_decode($m[2], true);
        if (!is_array($data)) return $m[0];
        preg_match_all('/<details><summary[^>]*>(.*?)<\/summary><p[^>]*>(.*?)<\/p><\/details>/s', $html, $faq, PREG_SET_ORDER);
        $plain = fn($s) => trim(preg_replace('/\s+/', ' ', html_entity_decode(strip_tags($s), ENT_QUOTES | ENT_HTML5, 'UTF-8')));
        foreach ($data['@graph'] as &$node) {
            if ($node['@type'] === 'SoftwareApplication') {
                if ($description) $node['description'] = $plain(lookup($dict, 'meta.description') ?? $node['description']);
                $node['url'] = $url;
                $node['inLanguage'] = $lang;
            }
            if ($node['@type'] === 'FAQPage' && $faq) {
                $node['inLanguage'] = $lang;
                $node['mainEntity'] = array_map(fn($f) => [
                    '@type' => 'Question',
                    'name' => $plain($f[1]),
                    'acceptedAnswer' => ['@type' => 'Answer', 'text' => $plain($f[2])],
                ], $faq);
            }
        }
        unset($node);
        $json = json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        return $m[1] . "\n" . $json . "\n  " . $m[3];
    }, $html, 1);
}
